CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(255),
    email VARCHAR2(255),
    senha VARCHAR2(255)
);

CREATE TABLE residuos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR2(255),
    peso NUMBER,
    destino VARCHAR2(255)
);

CREATE TABLE coletas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco VARCHAR2(255),
    data_coleta DATE,
    status VARCHAR2(255)
);